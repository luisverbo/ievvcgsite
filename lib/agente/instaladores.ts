/*
 * Mac e Linux. A extensão .command é o que faz o Finder abrir com dois
 * cliques; o arquivo precisa sair do .zip já executável (veja unixPermissions
 * na rota de download), senão o duplo clique não faz nada.
 */
export const INSTALAR_COMMAND = [
  "#!/bin/bash",
  'cd "$(dirname "$0")/agente" || { echo "Nao encontrei a pasta agente. Descompacte o .zip inteiro."; read -r; exit 1; }',
  "",
  "echo",
  'echo "  ============================================"',
  'echo "    PAGINAPRO - INSTALACAO DO AGENTE"',
  'echo "  ============================================"',
  "echo",
  "",
  "if ! command -v node >/dev/null 2>&1; then",
  '  echo "  O Node ainda nao esta neste computador."',
  '  echo "  Ele e gratuito e o agente precisa dele."',
  "  echo",
  "  if command -v brew >/dev/null 2>&1; then",
  '    read -r -p "  Posso instalar agora com o Homebrew? [s/N] " r',
  '    if [ "$r" = "s" ] || [ "$r" = "S" ]; then',
  "      brew install node",
  "    else",
  '      open "https://nodejs.org/en/download" 2>/dev/null || xdg-open "https://nodejs.org/en/download"',
  '      echo "  Instale o Node e clique aqui de novo."; read -r; exit 1',
  "    fi",
  "  else",
  '    echo "  Vou abrir o site do Node. Instale a versao LTS e clique aqui de novo."',
  '    open "https://nodejs.org/en/download" 2>/dev/null || xdg-open "https://nodejs.org/en/download"',
  "    read -r; exit 1",
  "  fi",
  "fi",
  "",
  'echo "  [1 de 2] Baixando os componentes do agente..."',
  "npm install || { echo; echo \"  Algo deu errado. Mande um print para o suporte.\"; read -r; exit 1; }",
  "echo",
  'echo "  [2 de 2] Instalando o navegador que o agente usa..."',
  "npx --yes playwright install chromium || { echo; echo \"  Algo deu errado. Mande um print para o suporte.\"; read -r; exit 1; }",
  "",
  "echo",
  'echo "  ============================================"',
  'echo "    PRONTO! Agora feche esta janela e abra"',
  'echo "    o LIGAR-AGENTE.command"',
  'echo "  ============================================"',
  "echo",
  'read -r -p "  Aperte Enter para fechar."',
  "",
].join("\n");

