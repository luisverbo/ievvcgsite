import "server-only";

/*
 * Instaladores de duplo clique — o que elimina o terminal da vida do cliente.
 *
 * O passo "abra o terminal DENTRO da pasta" era onde a instalação morria: quem
 * não é técnico não sabe fazer isso, e explicar por escrito não resolve (muda
 * de Windows para Mac, e no Windows mudou entre versões). Estes arquivos
 * resolvem sozinhos: `%~dp0` (Windows) e `dirname "$0"` (Mac/Linux) dão a
 * pasta do próprio script, então ele entra no lugar certo independente de onde
 * o cliente descompactou — Área de Trabalho, Downloads, tanto faz.
 *
 * Os .bat vão SEM ACENTO de propósito: o console do Windows ainda erra
 * acentuação dependendo da região, e "InstalaÃ§Ã£o" na tela assusta mais do
 * que texto simples.
 *
 * Node ausente não vira beco sem saída: no Windows tentamos instalar pelo
 * winget (já vem no Windows 10/11) e, sem ele, abrimos o site sozinho.
 */

const crlf = (linhas: string[]) => linhas.join("\r\n");

export const INSTALAR_BAT = crlf([
  "@echo off",
  "chcp 65001 >nul",
  "title PaginaPro - Instalar o agente",
  "setlocal",
  "",
  "echo.",
  "echo   ============================================",
  "echo     PAGINAPRO - INSTALACAO DO AGENTE",
  "echo   ============================================",
  "echo.",
  "echo   Isto leva alguns minutos. Pode deixar rodando.",
  "echo.",
  "",
  'cd /d "%~dp0agente" || goto ERRO_PASTA',
  "",
  "where node >nul 2>nul",
  "if errorlevel 1 goto SEM_NODE",
  "",
  "echo   [1 de 2] Baixando os componentes do agente...",
  "echo.",
  "call npm install",
  "if errorlevel 1 goto ERRO",
  "",
  "echo.",
  "echo   [2 de 2] Instalando o navegador que o agente usa...",
  "echo.",
  "call npx --yes playwright install chromium",
  "if errorlevel 1 goto ERRO",
  "",
  "echo.",
  "echo   ============================================",
  "echo     PRONTO! Instalacao concluida.",
  "echo.",
  "echo     Agora feche esta janela e clique duas vezes",
  "echo     em LIGAR-AGENTE para comecar a usar.",
  "echo   ============================================",
  "echo.",
  "pause",
  "exit /b 0",
  "",
  ":SEM_NODE",
  "echo   O Node ainda nao esta neste computador.",
  "echo   Ele e gratuito e o agente precisa dele para funcionar.",
  "echo.",
  "where winget >nul 2>nul",
  "if errorlevel 1 goto ABRIR_SITE",
  'choice /c SN /n /m "  Posso instalar o Node agora, automaticamente? [S/N]: "',
  "if errorlevel 2 goto ABRIR_SITE",
  "echo.",
  "echo   Instalando o Node. Se aparecer uma janela pedindo permissao, aceite.",
  "echo.",
  "winget install --id OpenJS.NodeJS.LTS -e --accept-source-agreements --accept-package-agreements",
  "echo.",
  "echo   ============================================",
  "echo     Node instalado!",
  "echo.",
  "echo     FECHE esta janela e clique duas vezes em",
  "echo     INSTALAR-AGENTE outra vez para continuar.",
  "echo   ============================================",
  "echo.",
  "pause",
  "exit /b 0",
  "",
  ":ABRIR_SITE",
  "echo.",
  "echo   Vou abrir o site do Node no seu navegador.",
  "echo   Baixe a versao LTS, instale, e depois clique",
  "echo   duas vezes em INSTALAR-AGENTE outra vez.",
  "echo.",
  "start https://nodejs.org/en/download",
  "pause",
  "exit /b 1",
  "",
  ":ERRO_PASTA",
  "echo   Nao encontrei a pasta 'agente'.",
  "echo   Descompacte o arquivo .zip inteiro antes de clicar aqui.",
  "echo   (No Windows: botao direito no .zip, 'Extrair tudo')",
  "pause",
  "exit /b 1",
  "",
  ":ERRO",
  "echo.",
  "echo   Algo deu errado na instalacao.",
  "echo   Tire um print desta janela inteira e mande para o suporte.",
  "echo.",
  "pause",
  "exit /b 1",
  "",
]);

