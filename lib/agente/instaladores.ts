  '    read -r -p "  Posso instalar agora com o Homebrew? [s/N] " r',
  '    if [ "$r" = "s" ] || [ "$r" = "S" ]; then',
  "      brew install node",
  "    else",
  '      open "https://nodejs.org/en/download" 2>/dev/null || xdg-open "https://nodejs.org/en/download"',
