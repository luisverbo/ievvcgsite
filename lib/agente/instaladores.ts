  "  else",
  '    echo "  Vou abrir o site do Node. Instale a versao LTS e clique aqui de novo."',
  '    open "https://nodejs.org/en/download" 2>/dev/null || xdg-open "https://nodejs.org/en/download"',
  "    read -r; exit 1",
  "  fi",
  "fi",
  "",
  "instalar() {",
  '  echo "  [1 de 2] Baixando os componentes do agente..."',
  "  npm install --no-audit --no-fund || return 1",
  "  echo",
  '  echo "  [2 de 2] Instalando o navegador que o agente usa..."',
  "  npx --yes playwright install chromium || return 1",
  "  return 0",
  "}",
  "",
  "if ! instalar; then",
  "  # Rede de segurança: falhou aqui, refaz na pasta local antes de desistir.",
  '  if [ "$MOVEU" = "0" ]; then',
  "    echo",
  '    echo "  Nao funcionou nesta pasta. Tentando numa pasta local..."',
  "    echo",
  '    mkdir -p "$DESTINO"',
  '    rsync -a --exclude node_modules "$RAIZ/" "$DESTINO/" 2>/dev/null || cp -R "$RAIZ/." "$DESTINO/"',
  '    cd "$DESTINO/agente" || { read -r; exit 1; }',
  "    MOVEU=1",
